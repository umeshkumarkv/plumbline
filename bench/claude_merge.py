#!/usr/bin/env python3
"""Merge generated content into a CLAUDE.md without touching what people wrote (deterministic, no LLM).

  claude_merge.py --target PATH --block ID --from DRAFT [--title "Heading"] [--write]

Generated content lives between markers:
    <!-- plumbline:begin ID -->
    ...
    <!-- plumbline:end ID -->
- the file does not exist      -> it is created with the block
- the file has block ID        -> only that block is replaced
- the file has no block ID     -> the block is appended at the end; every existing line is kept
Without --write it prints the unified diff (for the Write Guard); with --write it writes and prints the diff.
Exit 0 ok, 2 usage error (e.g. a marker without its pair).
"""
import argparse
import difflib
import re
import sys
from pathlib import Path


def merged(old: str, block_id: str, body: str, title: str | None) -> str:
    for legacy in ("agentic-sdlc",):               # markers written before 1.10 are adopted and renamed
        old = old.replace(f"<!-- {legacy}:begin {block_id} -->", f"<!-- plumbline:begin {block_id} -->") \
                 .replace(f"<!-- {legacy}:end {block_id} -->", f"<!-- plumbline:end {block_id} -->")
    begin, end = f"<!-- plumbline:begin {block_id} -->", f"<!-- plumbline:end {block_id} -->"
    note = "<!-- generated by /plumbline-onboard; edit outside these markers, or re-run the loop -->"
    inner = (f"## {title}\n\n" if title else "") + body.strip("\n") + "\n"
    block = f"{begin}\n{note}\n{inner}{end}\n"
    nb, ne = old.count(begin), old.count(end)
    if nb != ne or nb > 1:
        raise SystemExit(f"claude_merge: block '{block_id}' markers are unbalanced or repeated ({nb} begin, {ne} end)")
    if nb == 1:
        pat = re.compile(re.escape(begin) + r".*?" + re.escape(end) + r"\n?", re.S)
        return pat.sub(lambda _m: block, old, count=1)
    if not old.strip():
        return block
    return old.rstrip("\n") + "\n\n" + block


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", required=True)
    ap.add_argument("--block", required=True)
    ap.add_argument("--from", dest="src", required=True)
    ap.add_argument("--title")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    if not re.fullmatch(r"[a-z0-9][\w.-]*", a.block):
        print("claude_merge: --block must be a simple id (e.g. onboard, solution)", file=sys.stderr)
        return 2
    t = Path(a.target)
    old = t.read_text() if t.exists() else ""
    body = Path(a.src).read_text()
    body = re.sub(r"\A# CLAUDE\.md[^\n]*\n", "", body)          # the draft's own H1 would duplicate the file's
    try:
        new = merged(old, a.block, body, a.title)
    except SystemExit as e:
        print(e, file=sys.stderr)
        return 2
    sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), new.splitlines(True), f"a/{t}", f"b/{t}"))
    action = "replaced" if re.search(r"(plumbline|agentic-sdlc):begin " + re.escape(a.block) + " ", old) else "added"
    print(f"\nclaude_merge: {t} — block '{a.block}' {action}; "
          f"{len(old.splitlines())} → {len(new.splitlines())} lines")
    if a.write:
        t.parent.mkdir(parents=True, exist_ok=True)
        t.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
